-- Completa columnas introducidas desde la primera versión del esquema PG.
-- ADD COLUMN IF NOT EXISTS permite migrar instalaciones existentes y no-op
-- sobre instalaciones recién creadas desde schema.postgres.sql.
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS failed_attempts INTEGER NOT NULL DEFAULT 0;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS locked_until TEXT;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS totp_secret TEXT;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS totp_pending_secret TEXT;
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS totp_enabled SMALLINT NOT NULL DEFAULT 0;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS owner_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS provider TEXT NOT NULL DEFAULT 'supabase';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS owner_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS provider TEXT NOT NULL DEFAULT 'supabase';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS backup_options TEXT;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS schedule TEXT;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS archived SMALLINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    rol TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS access_token_revocations (
    jti TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS backup_jobs (
    id TEXT PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    started_at TEXT,
    finished_at TEXT,
    history_id BIGINT REFERENCES backup_history(id) ON DELETE SET NULL,
    detail TEXT,
    UNIQUE (requested_by, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_accounts_owner ON accounts (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_projects_owner ON projects (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_backup_history_project ON backup_history (project_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_log (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_user ON refresh_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_expiry ON refresh_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_access_token_revocations_expiry ON access_token_revocations (expires_at);
CREATE INDEX IF NOT EXISTS idx_backup_jobs_queue ON backup_jobs (status, created_at);
