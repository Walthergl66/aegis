-- Esquema PostgreSQL de Aegis. Las tablas privadas no se exponen por Data API.
CREATE SCHEMA IF NOT EXISTS identity;
CREATE SCHEMA IF NOT EXISTS integrations;
CREATE SCHEMA IF NOT EXISTS app;
CREATE SCHEMA IF NOT EXISTS backups;
CREATE SCHEMA IF NOT EXISTS audit;

CREATE TABLE IF NOT EXISTS identity.app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'admin',
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    totp_secret TEXT,
    totp_pending_secret TEXT,
    totp_enabled SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS integrations.accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES identity.app_users(id) ON DELETE SET NULL,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    pat_encrypted TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS app.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES identity.app_users(id) ON DELETE SET NULL,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    account_id BIGINT NOT NULL REFERENCES integrations.accounts(id),
    connection_encrypted TEXT NOT NULL,
    project_ref TEXT NOT NULL DEFAULT '',
    backup_options TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    schedule TEXT,
    archived SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS backups.backup_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES app.projects(id) ON DELETE CASCADE,
    fecha TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    tamaño_archivo DOUBLE PRECISION,
    resultado TEXT NOT NULL,
    ruta_archivo TEXT,
    detalle TEXT
);

CREATE TABLE IF NOT EXISTS audit.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id BIGINT REFERENCES identity.app_users(id) ON DELETE SET NULL,
    project_id BIGINT REFERENCES app.projects(id) ON DELETE SET NULL,
    accion TEXT NOT NULL,
    resultado TEXT NOT NULL,
    detalle TEXT,
    timestamp TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS identity.refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES identity.app_users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    rol TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS identity.access_token_revocations (
    jti TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS backups.backup_jobs (
    id TEXT PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES app.projects(id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES identity.app_users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    started_at TEXT,
    finished_at TEXT,
    history_id BIGINT REFERENCES backups.backup_history(id) ON DELETE SET NULL,
    detail TEXT,
    UNIQUE (requested_by, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_accounts_owner ON integrations.accounts (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_projects_owner ON app.projects (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_backup_history_project ON backups.backup_history (project_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit.audit_log (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_user ON identity.refresh_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_expiry ON identity.refresh_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_access_token_revocations_expiry ON identity.access_token_revocations (expires_at);
CREATE INDEX IF NOT EXISTS idx_backup_jobs_queue ON backups.backup_jobs (status, created_at);

ALTER TABLE identity.app_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE integrations.accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE backups.backup_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit.audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE identity.refresh_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE identity.access_token_revocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE backups.backup_jobs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON SCHEMA identity, integrations, app, backups, audit
    FROM PUBLIC;
