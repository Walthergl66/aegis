-- Esquema PostgreSQL para el backend de Backups Supabase.
-- No inserta usuarios, cuentas, proyectos ni datos de ejemplo.

CREATE TABLE IF NOT EXISTS web_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'admin',
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    totp_secret TEXT,
    totp_pending_secret TEXT,
    totp_enabled SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES web_users(id) ON DELETE SET NULL,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    pat_encrypted TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES web_users(id) ON DELETE SET NULL,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    connection_encrypted TEXT NOT NULL,
    project_ref TEXT NOT NULL DEFAULT '',
    backup_options TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    schedule TEXT,
    archived SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_chat_id BIGINT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'usuario',
    supabase_pat_encrypted TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    can_backup SMALLINT NOT NULL DEFAULT 0,
    can_monitor SMALLINT NOT NULL DEFAULT 0,
    UNIQUE (user_id, project_id)
);

CREATE TABLE IF NOT EXISTS backup_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    fecha TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    tamaño_archivo DOUBLE PRECISION,
    resultado TEXT NOT NULL,
    ruta_archivo TEXT,
    detalle TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    web_user_id BIGINT,
    project_id BIGINT,
    accion TEXT NOT NULL,
    resultado TEXT NOT NULL,
    detalle TEXT,
    timestamp TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES web_users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    rol TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS access_token_revocations (
    jti TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS backup_jobs (
    id TEXT PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES web_users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    started_at TEXT,
    finished_at TEXT,
    history_id BIGINT REFERENCES backup_history(id) ON DELETE SET NULL,
    detail TEXT,
    UNIQUE (requested_by, idempotency_key)
);

CREATE INDEX IF NOT EXISTS idx_accounts_owner ON accounts (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_projects_owner ON projects (owner_user_id);
CREATE INDEX IF NOT EXISTS idx_backup_history_project ON backup_history (project_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_permissions_user ON permissions (user_id);
CREATE INDEX IF NOT EXISTS idx_permissions_project ON permissions (project_id);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_log (timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_user ON refresh_sessions (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_sessions_expiry ON refresh_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_access_token_revocations_expiry ON access_token_revocations (expires_at);
CREATE INDEX IF NOT EXISTS idx_backup_jobs_queue ON backup_jobs (status, created_at);

-- El acceso a estas tablas se realiza solo a través del backend privado.
-- La API móvil no recibe credenciales de PostgreSQL ni privilegios Data API.
ALTER TABLE web_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE backup_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE refresh_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE access_token_revocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE backup_jobs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE web_users, accounts, projects, users, permissions,
    backup_history, audit_log, refresh_sessions, access_token_revocations,
    backup_jobs FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
