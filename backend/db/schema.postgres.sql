-- Esquema PostgreSQL para el backend de Backups Supabase.
-- No inserta usuarios, cuentas, proyectos ni datos de ejemplo.

CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    rol TEXT NOT NULL DEFAULT 'admin',
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TEXT,
    totp_secret TEXT,
    totp_pending_secret TEXT,
    totp_enabled SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    pat_encrypted TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    slug TEXT NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    provider TEXT NOT NULL DEFAULT 'supabase',
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    connection_encrypted TEXT NOT NULL,
    project_ref TEXT NOT NULL DEFAULT '',
    backup_options TEXT,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    activo SMALLINT NOT NULL DEFAULT 1,
    schedule TEXT,
    archived SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS backup_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    fecha TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    tamaño_archivo DOUBLE PRECISION,
    resultado TEXT NOT NULL,
    ruta_archivo TEXT,
    detalle TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id BIGINT,
    project_id BIGINT,
    accion TEXT NOT NULL,
    resultado TEXT NOT NULL,
    detalle TEXT,
    timestamp TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    rol TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    expires_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS access_token_revocations (
    jti TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS backup_jobs (
    id TEXT PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    requested_by BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    started_at TEXT,
    finished_at TEXT,
    history_id BIGINT REFERENCES backup_history(id) ON DELETE SET NULL,
    detail TEXT,
    UNIQUE (requested_by, idempotency_key)
);

-- El acceso a estas tablas se realiza solo a través del backend privado.
-- La API móvil no recibe credenciales de PostgreSQL ni privilegios Data API.
ALTER TABLE app_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE backup_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE refresh_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE access_token_revocations ENABLE ROW LEVEL SECURITY;
ALTER TABLE backup_jobs ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE app_users, accounts, projects,
    backup_history, audit_log, refresh_sessions, access_token_revocations,
    backup_jobs FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
